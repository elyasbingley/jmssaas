-- Fixes a real gap found while testing: there was no way to actually EMAIL
-- a quote/invoice to a client from the app. "Generate & share approval
-- link" (quotes/invoices detail screens) only ever handed the link to the
-- native OS Share sheet - the admin had to manually pick an app (which
-- might not even be email) and manually send it themselves, completely
-- outside this app's own email infrastructure. Worse, that action was
-- entirely disconnected from the Status chip that actually matters:
-- schedule_quote_communications/schedule_invoice_communications (the whole
-- reminder-ladder engine built in the two prior migrations) only fires
-- when `status` transitions to 'sent', which an admin sets independently -
-- so the reminder ladder could silently never fire (status flipped without
-- ever sending anything) or a quote could genuinely be shared without the
-- ladder ever starting (status never flipped).
--
-- Fix: two new trigger_keys, 'quote_sent'/'invoice_sent' - MANUAL triggers
-- the mobile app inserts directly (same shape as 'job_on_the_way'/
-- 'job_review_request', not touched by schedule_quote_communications/
-- schedule_invoice_communications, which continue to only handle the
-- follow-up ladder). The mobile app's new "Send via Email" button (see
-- apps/mobile/app/(tabs)/sales/quotes/[id].tsx and .../invoices/[id].tsx)
-- does both things this action always needed to do together: actually
-- deliver the email via process-scheduled-comms's immediate-dispatch path,
-- AND set status = 'sent' in the same action, so the two are no longer
-- separate steps an admin could forget or do out of order.

create or replace function public.seed_default_communication_rules(p_tenant_id uuid)
returns void
language plpgsql
as $$
begin
  insert into public.communication_rules (tenant_id, trigger_key, delay_offset_value, delay_offset_unit, delay_direction, channel)
  values
    (p_tenant_id, 'quote_stage_1', 3, 'days', 'after', 'email'),
    (p_tenant_id, 'quote_stage_2', 7, 'days', 'after', 'email'),
    (p_tenant_id, 'invoice_pre_due', 2, 'days', 'before', 'email'),
    (p_tenant_id, 'invoice_overdue_1', 3, 'days', 'after', 'email'),
    (p_tenant_id, 'job_review_request', 0, 'hours', 'after', 'email'),
    (p_tenant_id, 'job_on_the_way', 0, 'hours', 'after', 'email'),
    (p_tenant_id, 'quote_expiring_soon', 7, 'days', 'before', 'email'),
    (p_tenant_id, 'quote_expired', 0, 'days', 'after', 'email'),
    (p_tenant_id, 'invoice_due_today', 0, 'days', 'after', 'email'),
    (p_tenant_id, 'invoice_overdue_14', 14, 'days', 'after', 'email'),
    (p_tenant_id, 'invoice_payment_received', 0, 'hours', 'after', 'email'),
    (p_tenant_id, 'quote_sent', 0, 'hours', 'after', 'email'),
    (p_tenant_id, 'invoice_sent', 0, 'hours', 'after', 'email')
  on conflict (tenant_id, trigger_key) do nothing;
end;
$$;

